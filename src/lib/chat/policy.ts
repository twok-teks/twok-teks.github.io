/** Cheap denials for obvious misuse; ambiguous and contextual questions go to semantic scope checking. */
export function isClearlyOutsideScope(question: string): boolean {
  const normalized = question.normalize("NFKC").toLowerCase();
  const injectionPatterns = [
    /\b(?:ignore|disregard|override|bypass|forget)\b[\s\S]{0,70}\b(?:instructions?|rules?|policy|policies|guardrails?|restrictions?|system|sources?)\b/,
    /\b(?:reveal|show|print|repeat|dump|expose|give|extract|send)\b[\s\S]{0,90}\b(?:system prompt|developer (?:message|prompt)|hidden instructions?|api[ _-]?keys?|credentials?|environment variables?|private keys?|secret keys?|chain.of.thought|internal prompt)\b/,
    /\b(?:system prompt|developer message|hidden instructions?|groq_api_key|process\.env|\.env\.local|chain.of.thought)\b/,
    /\b(?:pretend|act|roleplay|behave)\b[\s\S]{0,45}\b(?:unrestricted|unfiltered|developer|system|jailbroken|without rules)\b/,
    /(?:<\/?(?:system|developer)>|\[INST\]|\[\/?SYSTEM\]|<\|(?:system|im_start)\|>)/i,
    /\b(?:send|post|upload|exfiltrate)\b[\s\S]{0,70}\b(?:prompt|secrets?|conversation|transcript|credentials?)\b/,
  ];
  if (injectionPatterns.some((pattern) => pattern.test(normalized)))
    return true;

  const generalTask =
    /\b(?:write|generate|implement|debug|fix|refactor|solve|create|build|design)\b[\s\S]{0,65}\b(?:code|script|function|program|algorithm|sql|regex|api|app|website|component|python|javascript|typescript|java|c\+\+|homework|essay|poem|story|recipe|itinerary)\b/;
  // "How did he build ..." seeks a description of documented work, not a new deliverable.
  const historicalQuestion =
    /\b(?:did|does|has|had)\b[\s\S]{0,30}\b(?:khanh|he|his|the project|gitguide)\b|\b(?:khanh|he|gitguide)\b[\s\S]{0,20}\b(?:built|created|implemented|used|developed)\b/;
  if (generalTask.test(normalized) && !historicalQuestion.test(normalized))
    return true;

  const obviouslyUnrelated =
    /\b(?:weather forecast|today.s weather|capital of|stock price|sports score|who won the game|plan (?:a|my) (?:trip|vacation)|write (?:me )?a (?:poem|song)|recipe for|solve this equation|latest news)\b/;
  return obviouslyUnrelated.test(normalized);
}

export function safeSourceUrl(value: string): boolean {
  if (value.length > 2_048 || /[\s\\\u0000-\u001f]/.test(value)) return false;
  if (value.startsWith("/") && !value.startsWith("//")) return true;
  try {
    const url = new URL(value);
    return url.protocol === "https:" && !url.username && !url.password;
  } catch {
    return false;
  }
}

/** No provider URL, HTML, unknown source ID, or unvalidated answer reaches the client. */
export function parseGroundedReply(
  text: string,
  documents: SourceDocument[],
): ChatReply | null {
  let result: unknown;
  try {
    result = JSON.parse(text);
  } catch {
    return null;
  }
  if (!result || typeof result !== "object" || Array.isArray(result))
    return null;
  const candidate = result as Record<string, unknown>;
  if (
    Object.keys(candidate).sort().join(",") !== "answer,inScope,sourceIds" ||
    typeof candidate.inScope !== "boolean" ||
    typeof candidate.answer !== "string" ||
    !Array.isArray(candidate.sourceIds) ||
    !candidate.sourceIds.every((id) => typeof id === "string")
  )
    return null;

  if (!candidate.inScope) return { reply: SCOPE_REPLY };
  const answer = candidate.answer.trim();
  if (
    !answer ||
    answer.length > MAX_ASSISTANT_CHARACTERS ||
    /(?:https?:\/\/|www\.|javascript:|data:text|file:\/\/|gsk_[a-z0-9]{16,}|groq_api_key|<\/?[a-z][^>]*>|```)/i.test(
      answer,
    ) ||
    candidate.sourceIds.length < 1 ||
    candidate.sourceIds.length > 5
  )
    return null;

  const catalogue = new Map(
    documents.map((document) => [document.id, document]),
  );
  const ids = [...new Set(candidate.sourceIds as string[])];
  const sources = [];
  for (const id of ids) {
    const source = catalogue.get(id);
    if (!source || !safeSourceUrl(source.url)) return null;
    sources.push({ label: source.label, url: source.url });
  }
  return { reply: answer, sources };
}
